--------------------------------------------- CTE ---------------------------------------------------------------------------------------------------------------
-- Q) Create a CTE to display all Hatchback cars. (Use - Simple CTE)
WITH hatchback_cars AS
(
    SELECT * FROM Cars_Table
    WHERE Segment = 'Hatchback'
)
SELECT * FROM hatchback_cars;

-- Q) Find total units sold by each dealer using CTE. (Use - CTE + Aggregate Function SUM())
WITH dealer_sales AS
(
    SELECT Dealer_Name,
    SUM(UnitsSold) AS TotalUnitsSold
    FROM Sales_Table
    GROUP BY Dealer_Name
)
SELECT * FROM dealer_sales;

-- Q) Show customer name with purchased car model using CTE. (Use - CTE + JOIN)
WITH customer_car AS
(
    SELECT c.Customer_Name,ca.Model
    FROM Consumer_Table c
    INNER JOIN Sales_Table s
    ON c.Customer_ID = s.Customer_ID
    INNER JOIN Cars_Table ca
    ON s.Car_ID = ca.Car_ID
)
SELECT * FROM customer_car;

-- Q) Find total revenue generated by each car model. (Use - Multiple CTE)
WITH model_sales AS
(
    SELECT s.Car_ID, s.UnitsSold,ca.Model,ca.OnRoadPrice
    FROM Sales_Table s
    INNER JOIN Cars_Table ca
    ON s.Car_ID = ca.Car_ID
),
model_revenue AS
(
    SELECT Model,SUM(OnRoadPrice * UnitsSold) AS Revenue
    FROM model_sales
    GROUP BY Model
)
SELECT * FROM model_revenue;

-- Q) Find top 2 most expensive cars using CTE. (Use - CTE + Ranking Function)
WITH ranked_cars AS
(
    SELECT Model,OnRoadPrice,
    DENSE_RANK() OVER(ORDER BY OnRoadPrice DESC) AS PriceRank
    FROM Cars_Table
)
SELECT * FROM ranked_cars
WHERE PriceRank <= 2;

-- Q) Find running total of sales using CTE. (Use - CTE + Windows Function)
WITH running_sales AS
(
    SELECT BookingDate,UnitsSold,
    SUM(UnitsSold) OVER(ORDER BY BookingDate) AS RunningTotal
    FROM Sales_Table
)
SELECT * FROM running_sales;